SUBSEC_3_2_3_TITLE = "3.2.3 Graph Topological Construction"
SUBSEC_3_2_3_PARAS = [
    (
        "For each client dataset, we construct a directed communication graph G = (V, E, X). Vertices V = {v_0, ..., v_{N-1}} represent unique IPv4 host "
        "addresses observed in local telemetry. Directed edges E subseteq V x V represent observed NetFlow conversations directed from source IP to destination IP. "
        "Edge attribute vectors e_{uv} in R^{d_e} contain the normalized domain-specialized flow features. Because message passing in Graph Attention Networks "
        "originates from vertex representations, initial node feature vectors x_u in R^{d_e} are computed by aggregating all incident edge attributes:"
    ),
    (
        "x_u = (1 / deg(u)) * sum_{(u, v) in E} e_{uv}    (Eq. 3.1)\n\n"
        "where deg(u) is the in-out degree of host u. This formulation establishes initial host representations reflecting average communication behaviors. "
        "IP addresses are strictly mapped to integer node indices (0 to N-1) and do not enter model inputs as features, ensuring structural generalizability."
    )
]

