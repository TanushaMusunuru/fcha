SUBSEC_3_2_1_TITLE = "3.2.1 Data Ingestion and RFC 793 TCP Flag Bitwise Decoding"
SUBSEC_3_2_1_PARAS = [
    (
        "Raw network telemetry logs cumulative TCP connection flags as a single integer (TCP_FLAGS) representing the bitwise OR of all control "
        "bits observed across the flow. In raw form, integer representation conceals critical connection handshake dynamics. For example, a TCP_FLAGS "
        "value of 18 corresponds to SYN + ACK (16 + 2), while a value of 24 corresponds to PSH + ACK (16 + 8). Treating TCP_FLAGS as a continuous "
        "scalar introduces erroneous numeric distance metrics into neural network convolutions."
    ),
    (
        "To expose granular transport layer state semantics, we implement bitwise mask extraction in accordance with RFC 793 specifications. "
        "The integer field is mapped to six discrete binary indicator features:\n"
        "• FIN (bit 0, mask 0x01): Connection teardown flag\n"
        "• SYN (bit 1, mask 0x02): Connection synchronization handshake flag\n"
        "• RST (bit 2, mask 0x04): Connection reset abort flag\n"
        "• PSH (bit 3, mask 0x08): Push data buffer to application layer flag\n"
        "• ACK (bit 4, mask 0x10): Acknowledgment received flag\n"
        "• URG (bit 5, mask 0x20): Urgent pointer field significant flag\n\n"
        "This bitwise decoding enables our GNN encoders to directly identify reconnaissance SYN scans, RST tear-down floods, and PSH payload bursts."
    )
]

SUBSEC_3_2_2_TITLE = "3.2.2 Feature Scaling and Domain-Specialized Feature Engineering"
SUBSEC_3_2_2_PARAS = [
    (
        "Continuous flow attributes—such as IN_BYTES, OUT_BYTES, IN_PKTS, OUT_PKTS, and FLOW_DURATION_MILLISECONDS—exhibit extreme positive skewness, "
        "with values spanning up to eight orders of magnitude. To stabilize stochastic gradient optimization, we apply a logarithmic transformation: "
        "x_scaled = log(x + 1), followed by standard z-score normalization: z = (x_scaled - mu) / sigma, where mean mu and standard deviation sigma "
        "are computed strictly over the training folds to eliminate test leakage."
    ),
    (
        "Rather than forcing a single GNN encoder to process all heterogeneous features simultaneously, we engineer three domain-specialized sub-feature "
        "vectors designed to isolate orthogonal attack dynamics (Table 3.4):\n"
        "1. Temporal Feature Set (21 features): Encodes dynamic flow rates, packet arrival rates (IN_PKTS / duration), byte rates (IN_BYTES / duration), "
        "forward packet proportion, and log-transformed duration. This detector specializes in identifying volumetric surges, including DDoS and DoS.\n"
        "2. Content Feature Set (22 features): Encodes payload asymmetries, average packet sizes (IN_BYTES / IN_PKTS), byte asymmetry ratios "
        "(IN_BYTES / (OUT_BYTES + 1)), SYN-to-packet ratio, and ACK proportions. This detector specializes in detecting web injection and XSS.\n"
        "3. Behavioral Feature Set (21 features): Encodes service port privilege indicators (ports < 1024), ephemeral port dispersion, transport protocol "
        "identifiers, and TCP flag combinations. This detector specializes in isolating administrative password guessing, backdoor beacons, and port scans."
    )
]

