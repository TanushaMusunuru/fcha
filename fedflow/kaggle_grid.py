"""Run the paper grid on Kaggle as many small kernels, then collect and merge the results.

    python -m fedflow.kaggle_grid upload-code                  # create/update the private code dataset
    python -m fedflow.kaggle_grid push --datasets nf_ton_iot_v2 --groups graph --splits signature --folds 0
    python -m fedflow.kaggle_grid push --dry-run               # show what would be pushed
    python -m fedflow.kaggle_grid queue --groups flat           # push as Kaggle session slots free up
    python -m fedflow.kaggle_grid status
    python -m fedflow.kaggle_grid collect                      # download new outputs, merge, summarise (--redownload: all)

Settings come from configs/fedflow/paper/kaggle.yaml. The Kaggle username is read from the
local Kaggle login. Each kernel runs one (dataset, split, fold, model group) with all seeds.
"""
from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any, Dict, Iterator, List, Tuple

import yaml

from .config import load_config

ROOT = Path(__file__).resolve().parents[1]
SETTINGS = ROOT / "configs" / "fedflow" / "paper" / "kaggle.yaml"
CODE_FILES = ["fedflow", "configs/fedflow", "kaggle/fedflow_kaggle.py", "requirements-fedflow.txt", "FEDFLOW.md"]

KERNEL_TEMPLATE = '''"""Generated by fedflow.kaggle_grid: {title}"""
import glob, os, sys
hits = glob.glob("/kaggle/input/**/fedflow/__init__.py", recursive=True)
if not hits:
    raise SystemExit("fedflow code dataset is not attached")
repo = os.path.dirname(os.path.dirname(hits[0]))
sys.path.insert(0, repo)
args = {args!r}
args[args.index("--config") + 1] = os.path.join(repo, args[args.index("--config") + 1])
from fedflow.run import main
main(args)
'''


def kaggle(*args: str, cwd: Path | None = None, check: bool = True, timeout: int = 600) -> str:
    cmd = [sys.executable, "-m", "kaggle.cli", *args]
    try:
        res = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        if check:
            raise RuntimeError(f"kaggle {' '.join(args)} timed out after {timeout}s")
        return f"timed out after {timeout}s"
    out = "\n".join(l for l in (res.stdout + res.stderr).splitlines() if "outdated" not in l)
    if check and res.returncode != 0:
        raise RuntimeError(f"kaggle {' '.join(args)} failed:\n{out}")
    return out


def username() -> str:
    from kaggle.api.kaggle_api_extended import KaggleApi
    api = KaggleApi()
    api.authenticate()
    name = api.config_values.get("username")
    if not name:
        raise SystemExit("Could not read the Kaggle username from the local Kaggle login.")
    return name


def settings() -> Dict[str, Any]:
    with open(SETTINGS, encoding="utf-8") as fh:
        return yaml.safe_load(fh)


# --------------------------------------------------------------------------- upload code

def upload_code(message: str) -> None:
    s, user = settings(), username()
    ref = f"{user}/{s['code_dataset_slug']}"
    with tempfile.TemporaryDirectory() as tmp:
        stage = Path(tmp)
        for rel in CODE_FILES:
            src = ROOT / rel
            dst = stage / rel
            if src.is_dir():
                shutil.copytree(src, dst, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
            else:
                dst.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(src, dst)
        (stage / "dataset-metadata.json").write_text(json.dumps(
            {"title": s["code_dataset_slug"], "id": ref, "licenses": [{"name": "CC0-1.0"}]}, indent=2))
        exists = ref in kaggle("datasets", "list", "--mine", check=False)
        if exists:
            print(kaggle("datasets", "version", "-p", ".", "-m", message, "--dir-mode", "zip", cwd=stage))
        else:
            print(kaggle("datasets", "create", "-p", ".", "--dir-mode", "zip", cwd=stage))


# --------------------------------------------------------------------------- kernels

def plan(datasets: List[str], groups: List[str], splits: List[str], folds: List[int]) -> Iterator[Tuple[str, str, str, int]]:
    for d in datasets:
        for sp in splits:
            for f in folds:
                for g in groups:
                    yield d, sp, g, f


def kernel_slug(prefix: str, tag: str, sp: str, f: int, g: str) -> str:
    slug = f"{prefix}-{tag}-{sp}-f{f}-{g}".replace("_", "-").lower()
    if len(slug) > 50:
        raise SystemExit(f"Kernel name {slug!r} is longer than Kaggle's 50 characters; shorten the tag or prefix.")
    return slug


def build_args(d: str, sp: str, f: int, gcfg: Dict[str, Any]) -> List[str]:
    cfg = load_config(ROOT / "configs" / "fedflow" / "paper" / f"{d}.yaml")
    split_spec = [s for s in cfg["splits"] if s["type"] == sp]
    if not split_spec:
        raise SystemExit(f"split {sp!r} not in paper config for {d}")
    return ["--config", f"configs/fedflow/paper/{d}.yaml",
            "--models", ",".join(gcfg["models"]), "--folds", str(f),
            "--set", f"splits={json.dumps(split_spec)}",
            "--set", f"experiment.results_dir=/kaggle/working/results",
            "--set", f"experiment.sanity_permuted_labels={str(bool(gcfg.get('sanity'))).lower()}"]


def push_one(s: Dict[str, Any], user: str, d: str, sp: str, g: str, f: int) -> Tuple[bool, str]:
    """Push one kernel. Returns (accepted, message); a rejected push (e.g. session limit) is False."""
    gcfg = s["groups"][g]
    slug = kernel_slug(s["kernel_prefix"], s["datasets"][d]["tag"], sp, f, g)
    args = build_args(d, sp, f, gcfg)
    with tempfile.TemporaryDirectory() as tmp:
        k = Path(tmp)
        (k / "run.py").write_text(KERNEL_TEMPLATE.format(title=f"{d} {sp} fold {f} {g}", args=args), encoding="utf-8")
        meta = {"id": f"{user}/{slug}", "title": slug, "code_file": "run.py", "language": "python",
                "kernel_type": "script", "is_private": bool(s.get("private", True)),
                "enable_gpu": bool(gcfg["gpu"]), "enable_internet": True,
                "dataset_sources": [f"{user}/{s['code_dataset_slug']}", s["datasets"][d]["data"]],
                "competition_sources": [], "kernel_sources": []}
        (k / "kernel-metadata.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
        out = kaggle("kernels", "push", "-p", ".", cwd=k, check=False).strip()
    last = out.splitlines()[-1] if out else ""
    return ("successfully pushed" in last), last


def push(datasets, groups, splits, folds, dry_run: bool) -> None:
    s = settings()
    user = username()
    for d, sp, g, f in plan(datasets, groups, splits, folds):
        slug = kernel_slug(s["kernel_prefix"], s["datasets"][d]["tag"], sp, f, g)
        if dry_run:
            print(f"[dry-run] {user}/{slug}  gpu={s['groups'][g]['gpu']}  data={s['datasets'][d]['data']}")
            continue
        ok, msg = push_one(s, user, d, sp, g, f)
        print(f"{'pushed  ' if ok else 'REJECTED'} {user}/{slug}: {msg}")


def kernel_state(ref: str) -> str:
    """'complete', 'running', 'queued', 'error', 'cancel...', 'missing', or 'unknown' when Kaggle
    could not be reached (network down, timeout), so a finished kernel is never pushed again."""
    out = kaggle("kernels", "status", ref, check=False, timeout=120)
    if "has status" in out:
        return out.split("has status", 1)[1].rsplit(".", 1)[-1].strip().strip('"').lower()
    if "Cannot access kernel" in out or "404" in out:
        return "missing"
    return "unknown"


def queue(datasets, groups, splits, folds) -> None:
    """Push every planned kernel while respecting Kaggle's concurrent-session limits. Kernels that
    already completed or are running are left alone, so the command can be re-run at any time."""
    import time
    s = settings()
    user = username()
    limits = s.get("max_running", {"cpu": 5, "gpu": 2})
    todo = list(plan(datasets, groups, splits, folds))
    print(f"queue: {len(todo)} kernels planned")
    while True:
        states = {}
        for d, sp, g, f in todo:
            ref = f"{user}/{kernel_slug(s['kernel_prefix'], s['datasets'][d]['tag'], sp, f, g)}"
            states[(d, sp, g, f)] = (ref, kernel_state(ref))
        busy = {"cpu": 0, "gpu": 0}
        for (d, sp, g, f), (_, st) in states.items():
            if st in ("running", "queued"):
                busy["gpu" if s["groups"][g]["gpu"] else "cpu"] += 1
        waiting = [k for k, (_, st) in states.items() if st == "missing"]
        done = sum(st == "complete" for _, st in states.values())
        failed = [ref for ref, st in states.values() if st in ("error", "cancelacknowledged", "cancelrequested")]
        print(f"{time.strftime('%H:%M:%S')} complete {done}/{len(todo)}  running cpu {busy['cpu']} gpu {busy['gpu']}  "
              f"waiting {len(waiting)}  failed {len(failed)}", flush=True)
        for ref in failed:
            print(f"  FAILED: {ref} (check its log; re-run after fixing)", flush=True)
        unknown = [ref for ref, st in states.values() if st == "unknown"]
        if unknown:
            print(f"  Kaggle unreachable for {len(unknown)} kernel(s); not pushing this round", flush=True)
            time.sleep(int(s.get("poll_seconds", 120)))
            continue
        for key in waiting:
            kind = "gpu" if s["groups"][key[2]]["gpu"] else "cpu"
            if busy[kind] >= int(limits[kind]):
                continue
            ok, msg = push_one(s, user, *key)
            print(f"  {'pushed' if ok else 'push rejected'}: {states[key][0]}  {'' if ok else msg}", flush=True)
            if ok:
                busy[kind] += 1
        if not waiting and busy["cpu"] == 0 and busy["gpu"] == 0:
            print("queue: all kernels finished", flush=True)
            return
        time.sleep(int(s.get("poll_seconds", 120)))


def status(prefix: str) -> None:
    print(kaggle("kernels", "list", "--mine", "--search", prefix, "--page-size", "100"))


def add_records(path: Path, seen: set, merged: list) -> None:
    """Append the records in a results.jsonl, giving older ones a location-independent run_key
    (computed from the config_used.json next to them) and skipping runs already merged."""
    from .config import deep_merge
    from .run import record_key, run_key
    used = path.parent / "config_used.json"
    cfg = json.loads(used.read_text(encoding="utf-8")) if used.exists() else None
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        rec = json.loads(line)
        if "run_key" not in rec and cfg is not None:
            sp_type = rec["split"].split("-")[0]
            scfg = next((sc for sc in cfg["splits"] if sc["type"] == sp_type), None)
            base_model = rec["model"].split("+")[0]
            if scfg is not None and base_model in cfg["models"]:
                scfg = deep_merge({"signature": cfg.get("signature", {}) or {}}, scfg)
                rec["run_key"] = run_key(cfg, scfg, cfg["models"][base_model], rec["dataset"], rec["split"],
                                         rec["fold"], rec["partition"], rec["seed"], rec["model"])
        key = record_key(rec)
        if key not in seen:
            seen.add(key)
            merged.append(json.dumps(rec))


def collect(datasets: List[str], redownload: bool = False) -> None:
    """Merge Kaggle outputs and local runs. Kernels already downloaded are reused unless `redownload`."""
    s = settings()
    user = username()
    listing = kaggle("kernels", "list", "--mine", "--search", s["kernel_prefix"], "--page-size", "100")
    refs = [line.split()[0] for line in listing.splitlines() if line.startswith(f"{user}/{s['kernel_prefix']}")]
    for d in datasets:
        out_dir = ROOT / "results" / "paper" / d
        dl_root = out_dir / "kaggle"
        dl_root.mkdir(parents=True, exist_ok=True)
        tag = s["datasets"][d]["tag"]
        seen, merged = set(), []
        for ref in refs:
            if f"-{tag}-" not in ref:
                continue
            dest = dl_root / ref.split("/")[1]
            if redownload or not any(dest.rglob("results.jsonl")):
                print(f"downloading {ref}", flush=True)
                kaggle("kernels", "output", ref, "-p", str(dest), check=False)
            for p in dest.rglob("results.jsonl"):
                add_records(p, seen, merged)
        for local in sorted(out_dir.glob("local*/results.jsonl")):   # runs done on this machine
            add_records(local, seen, merged)
        if not merged:
            print(f"{d}: no results downloaded yet")
            continue
        (out_dir / "results.jsonl").write_text("\n".join(merged) + "\n", encoding="utf-8")
        print(f"{d}: merged {len(merged)} runs -> {out_dir / 'results.jsonl'}")
        from .summarize import summarize
        cfg = load_config(ROOT / "configs" / "fedflow" / "paper" / f"{d}.yaml")
        summarize(out_dir / "results.jsonl", out_dir, cfg.get("summary", {}))


def main() -> None:
    s = settings()
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    u = sub.add_parser("upload-code")
    u.add_argument("-m", "--message", default="update")
    p = sub.add_parser("push")
    p.add_argument("--datasets", default=",".join(s["datasets"]))
    p.add_argument("--groups", default=",".join(s["groups"]))
    p.add_argument("--splits", default=",".join(s["splits"]))
    p.add_argument("--folds", default=",".join(map(str, s["folds"])))
    p.add_argument("--dry-run", action="store_true")
    q = sub.add_parser("queue", help="push kernels as session slots free up (safe to re-run)")
    q.add_argument("--datasets", default=",".join(s["datasets"]))
    q.add_argument("--groups", default=",".join(s["groups"]))
    q.add_argument("--splits", default=",".join(s["splits"]))
    q.add_argument("--folds", default=",".join(map(str, s["folds"])))
    sub.add_parser("status")
    c = sub.add_parser("collect")
    c.add_argument("--datasets", default=",".join(s["datasets"]))
    c.add_argument("--redownload", action="store_true", help="download every kernel again, even ones already downloaded")
    a = ap.parse_args()
    if a.cmd == "upload-code":
        upload_code(a.message)
    elif a.cmd == "push":
        push(a.datasets.split(","), a.groups.split(","), a.splits.split(","),
             [int(x) for x in a.folds.split(",")], a.dry_run)
    elif a.cmd == "queue":
        queue(a.datasets.split(","), a.groups.split(","), a.splits.split(","), [int(x) for x in a.folds.split(",")])
    elif a.cmd == "status":
        status(s["kernel_prefix"])
    else:
        collect(a.datasets.split(","), a.redownload)


if __name__ == "__main__":
    main()
